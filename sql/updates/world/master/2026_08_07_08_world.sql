-- script files) found 189 proc-dependent spells with zero spell_proc rows. Of those, 157
-- (this migration) have confirmed real native proc data in SpellAuraOptions.db2 for build
-- 7.3.5.26972 (ProcTypeMask/ProcChance/ProcCharges) - SpellMgr::LoadSpellProcs already falls
-- back to that native data whenever a spell_proc row's own fields are 0
-- (see SpellMgr.cpp ~line 1574), so a bare SpellId-only row is enough to restore function;
-- no per-spell values need to be hand-derived or guessed.
--
-- The remaining 32 (of the original 189) have no SpellAuraOptions data at all for this build
