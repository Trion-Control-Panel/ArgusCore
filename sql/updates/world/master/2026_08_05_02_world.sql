-- Port ArgusCore's missing dungeon-boss-detection subsystem. Both primary reference cores
-- (DestinyCore, AshamaneCore) strip CREATURE_FLAG_EXTRA_DUNGEON_BOSS from DB content and instead
-- set it dynamically at load time from an `instance_encounters` table (entry = DungeonEncounter
-- id, creditEntry = the creature that grants kill credit for it) via a LoadInstanceEncounters()
-- function - confirmed by their own header comments ("SET DYNAMICALLY, DO NOT ADD IN DB") and
-- matching implementations in both. ArgusCore had the CREATURE_FLAG_EXTRA_DB_ALLOWED mask
-- stripping the flag (correctly, matching upstream) but never had the table or the loader that's
-- supposed to restore it afterward - see CreatureData.h and the new ObjectMgr::LoadInstanceEncounters()
-- (wired into World.cpp's load sequence, ported from the reference cores and translated to
-- ArgusCore's actual CreatureTemplate shape, which unlike the older cores doesn't need a
-- DifficultyEntry[] loop since flags_extra isn't duplicated per difficulty here).
--
-- Data below is ported verbatim from DestinyCore's own Legion 7.3.5 world DB dump
-- (sql/DB_world_735.02.sql) - real historical boss-encounter data spanning Vanilla through Legion,
-- not fabricated. Verified against this DB directly (dry-run in a rolled-back transaction): all
-- 397 rows import cleanly, and 388/388 of its creature-credit encounters resolve to real entries
-- in this server's actual creature_template.
--
-- The 485 creature_template rows that already carried this flag as static DB content get it
-- stripped below, since it's now the loader's job to set it correctly and dynamically going
-- forward instead of trusting a snapshot that may be stale or incomplete.

CREATE TABLE IF NOT EXISTS `instance_encounters` (
  `entry` int unsigned NOT NULL COMMENT 'Unique entry from DungeonEncounter.db2',
  `creditType` tinyint unsigned NOT NULL DEFAULT '0',
  `creditEntry` int unsigned NOT NULL DEFAULT '0',
  `lastEncounterDungeon` smallint unsigned NOT NULL DEFAULT '0' COMMENT 'If not 0, LFGDungeons.db2 entry for the instance it is the last encounter in',
  `comment` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT '',
  PRIMARY KEY (`entry`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

